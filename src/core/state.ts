import { freshnessNote, versionNote, type RunFreshness } from './analysis.ts'
import type { IsoTime, Shape } from './events.ts'
import type { ProjectState } from './binder.ts'

export interface StateConfig {
  name: string
  created: IsoTime
}

function shortDate(value: IsoTime): string {
  return value.slice(0, 10)
}

/** Keep STATE.md skimmable: a narrative is a sentence for the reader, not a wall of text. */
function clip(text: string, limit = 160): string {
  return text.length <= limit ? text : `${text.slice(0, limit - 1).trimEnd()}…`
}

export function shapeSummary(shape: Shape | undefined): string {
  if (!shape) return 'missing shape'
  const fields = shape.fields
    .map((field) => `${field.name}:${field.type}${field.unit ? `[${field.unit}]` : ''}`)
    .join(', ')
  const time = shape.time_field === undefined ? '' : `; observation time: ${shape.time_field}`
  return `${shape.id} (${fields}${time})`
}

/**
 * STATE.md is generated, never written by hand, so it cannot drift from the log. It is the first
 * thing a fresh session reads; every line earns its place by answering "where did we leave this?".
 */
export interface RenderOptions {
  /**
   * Freshness per run id, computed by `assessRuns`. Passed in rather than computed here because it
   * needs the filesystem (the recipe files), and because the caller usually has it already.
   */
  freshness?: Map<string, RunFreshness>
}

export function renderState(config: StateConfig, state: ProjectState, options?: RenderOptions): string {
  const lines: string[] = []
  const datasets = [...state.datasets.values()]
  const totalPoints = datasets.reduce((sum, dataset) => sum + dataset.points.length, 0)
  const active = datasets.reduce(
    (sum, dataset) => sum + dataset.points.filter((point) => point.status === 'active').length,
    0,
  )

  lines.push('# STATE', '')
  lines.push(
    `**${config.name}** · created ${shortDate(config.created)} · ${active} active points (${totalPoints} recorded) · ${datasets.length} dataset(s)`,
  )
  lines.push('', '_Generated by `bench state`. Do not edit by hand; it is rewritten on every mutation._', '')

  lines.push('## Datasets', '')
  if (datasets.length === 0) {
    lines.push('_none yet_', '')
  } else {
    lines.push('| dataset | shape | version | active | recorded | first | last |')
    lines.push('|---|---|---|---|---|---|---|')
    for (const dataset of datasets) {
      const shape = state.shapes.get(dataset.shape)
      const first = dataset.points[0]?.tObserved.slice(0, 10) ?? '—'
      const last = dataset.points.at(-1)?.tObserved.slice(0, 10) ?? '—'
      const activeCount = dataset.points.filter((point) => point.status === 'active').length
      lines.push(
        `| ${dataset.id} | ${shape?.id ?? dataset.shape} | v${dataset.version} | ${activeCount} | ${dataset.points.length} | ${first} | ${last} |`,
      )
    }
    lines.push('')
    for (const dataset of datasets) {
      lines.push(`- \`${dataset.id}\` — ${shapeSummary(state.shapes.get(dataset.shape))}`)
    }
    lines.push('')
    // What each version was, in one line per version: the question "what did we have last week" is
    // asked far more often than it is answered by re-reading the log.
    lines.push('## Versions', '')
    for (const dataset of datasets) {
      for (const record of dataset.versions) {
        const diff = record.diff
          ? ` · +${record.diff.added} −${record.diff.removed} ~${record.diff.changed}`
          : ''
        const how = record.recorded ? record.source : 'inferred (rows recorded before versions were)'
        lines.push(
          `- \`${dataset.id}\` v${record.version} · ${record.rows} row(s) at creation${diff} · ${shortDate(record.at)} · ${how}`,
        )
      }
    }
    lines.push('')
  }

  if (state.runs.length > 0) {
    lines.push('## Analyses', '')
    for (const run of state.runs.slice(-6).reverse()) {
      const narrative = run.narrative ? ` — ${clip(run.narrative)}` : ''
      // Whether the result still holds is the first thing a reader needs, before the verdict: a
      // confident sentence about data that has since changed is the most expensive kind of stale.
      const freshness = options?.freshness?.get(run.id)
      const note = freshnessNote(freshness)
      const pinned = versionNote(freshness)
      const status = [pinned, note].filter((part) => part !== '').join(' · ')
      const suffix = status === '' ? '' : ` · ${status}`
      lines.push(`- \`${run.recipe}\` · **${run.verdict}** · ${shortDate(run.at)}${suffix}${narrative}`)
    }
    lines.push('')
  }

  if (state.decisions.length > 0) {
    lines.push('## Decisions', '')
    for (const decision of state.decisions.slice(-8)) {
      lines.push(`- ${shortDate(decision.at)} — ${decision.text}`)
    }
    lines.push('')
  }

  lines.push('## Health', '')
  if (state.problems.length === 0) {
    lines.push('- no structural problems')
  } else {
    for (const problem of state.problems) lines.push(`- ${problem}`)
  }
  lines.push('')

  return lines.join('\n')
}
